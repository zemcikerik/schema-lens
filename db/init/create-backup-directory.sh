#!/usr/bin/env bash
set -euo pipefail

pdb_name="${ORACLE_DATABASE:-FREEPDB1}"

sqlplus -s / as sysdba <<SQL
ALTER SESSION SET CONTAINER = ${pdb_name};
CREATE OR REPLACE DIRECTORY SCHEMA_LENS_BACKUP_DIR AS '/opt/oracle/backups';
GRANT READ, WRITE ON DIRECTORY SCHEMA_LENS_BACKUP_DIR TO ${APP_USER};
GRANT EXECUTE ON SYS.DBMS_DATAPUMP TO ${APP_USER};
SQL
